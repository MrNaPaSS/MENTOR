"""Опознаватель ученика на бирже.

UID у WEEX - число: партнёрская выгрузка отдаёт его цифрами, и цифрами же его
ждут ручки партнёрской программы. Приходит он к нам не оттуда: его вводит
ученик руками или передаёт бот, а по дороге к цифрам прилипает всё, что можно
скопировать вместе с ними - пробелы, дефисы, буквенный префикс из интерфейса
биржи.

10 сентября это стоило ученику №26 всей его статистики: в базе у него лежало
``PO6067083524``, партнёрская ручка отвечала на такой ``userId`` отказом
(HTTP 400), а в выгрузке оборотов строка искалась по той же строке с буквами -
и не находилась, потому что там он числом. Ни баланса, ни оборота: журнал
писал «оборот не с чего взять», и причину пришлось искать по логам биржи.

Поэтому опознаватель приводится к цифрам в одном месте - здесь, - а не в
каждом, кто собрался на биржу.
"""

from __future__ import annotations

import re

_DIGITS = re.compile(r"\D+")

# Длина настоящего UID. Ниже - обрывок строки или чужое число вроде года, выше -
# уже не опознаватель. У WEEX он семи-десятизначный; берём с запасом в обе
# стороны, чтобы не отказать живому ученику из-за нашей же таблицы.
MIN_LENGTH = 5
MAX_LENGTH = 20


def clean_uid(raw: str | int | None) -> str:
    """Только цифры опознавателя. Мусор на входе даёт пустую строку.

    ``' PO 6067083524 '`` -> ``'6067083524'``; ``None`` -> ``''``.
    """
    if raw is None:
        return ""
    return _DIGITS.sub("", str(raw))


def looks_like_uid(raw: str | int | None) -> bool:
    """Похоже ли это на опознаватель настолько, чтобы идти с ним на биржу.

    Дешёвая проверка перед запросом: поход с заведомо негодной строкой стоит
    отказа биржи, места в её счётчике запросов и строки «HTTP 400» в журнале,
    по которой ничего не понять.
    """
    digits = clean_uid(raw)
    return MIN_LENGTH <= len(digits) <= MAX_LENGTH


def uid_variants(raw: str | int | None) -> list[str]:
    """Написания опознавателя, под которыми он может лежать в базе.

    Сначала как есть, потом цифрами: ученик, заведённый до чистки, записан со
    своим префиксом, и искать его по цифрам значит не найти и завести второго.
    Пустые и повторяющиеся написания отсеиваются.
    """
    out: list[str] = []
    for one in (str(raw).strip() if raw is not None else "", clean_uid(raw)):
        if one and one not in out:
            out.append(one)
    return out
