"""VIP тем, кто пришёл через академию.

Трейдер, зарегистрировавший биржевой счёт по ссылке академии, - реферал нашей
партнёрской программы. Ему сразу открыто всё: все инструменты терминала и
выгрузка журнала (backend/entitlements.py, VIP_FEATURES), а на бирже - скидка
на комиссию. Кто подключает свой счёт без нашей ссылки, торгует так же, но
инструменты покупает за монеты NMNH.

Реферала узнаём по ответу партнёрской ручки биржи: по чужому UID она данных
не отдаёт. Проверка уже стоит везде, где UID приходит к нам, - при входе, при
выдаче пароля ботом, при сборе снимков баланса. Здесь только правило, что с её
результатом делать, - одно на всех, кто проверяет.

Решение ментора сильнее автоматики: снял VIP руками - сервер его не вернёт,
выдал руками - не отберёт.
"""

from __future__ import annotations

import logging

from core.models import Student

logger = logging.getLogger("nmnh.referral")

# Откуда у ученика VIP.
REFERRAL = "referral"   # подтверждён рефералом партнёрки - выдан сервером
MANUAL = "manual"       # решение ментора в админке


def grant_referral_vip(student: Student) -> bool:
    """Открыть VIP подтверждённому рефералу. True - открыли сейчас.

    Коммит за вызывающим. Не трогаем, если VIP уже есть или ментор решил
    сам - в любую сторону.
    """
    if student.is_vip or (student.vip_source or "") == MANUAL:
        return False
    student.is_vip = True
    student.vip_source = REFERRAL
    logger.info("VIP за регистрацию через академию: ученик %s, UID %s", student.id, student.weex_uid)
    return True
