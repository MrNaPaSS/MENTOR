// Звуки терминала.
//
// Скальпер смотрит в стакан, а не в ярлык позиции: цель может взяться, пока он
// разглядывает другую монету. Звук сообщает о событии, не требуя взгляда, — это
// его единственная задача, поэтому сигналы короткие и разные на слух.
//
// Тоны синтезируются, а не грузятся файлами: файл — это ещё один запрос,
// который может не дойти, и лишний вес в сборке ради полусекунды писка.
// Заодно ничего не нужно раздавать со стороннего домена.
//
// Браузер не даёт играть до первого действия пользователя, поэтому звуковой
// контекст создаётся лениво — на первом же событии после клика он уже готов.

import { duck } from "./radio";

export type SoundKind =
  /** Заявка ушла на биржу. */
  | "order"
  /** Цена дошла до уровня, позиция набрана. */
  | "entry"
  /** Взята цель. */
  | "take"
  /** Сделка отработала полностью. */
  | "profit"
  /** Сработал стоп. */
  | "stop"
  /** Позиция зафиксирована руками. */
  | "close"
  /** Биржа отказала. */
  | "error"
  /** Цена пересекла отмеченный уровень. */
  | "alert"
  /** Пришла награда - ждёт, пока её заберут. */
  | "reward"
  /** Награду забрали: монеты ушли в баланс. */
  | "claim";

type Tone = {
  /** Частоты по порядку: одна нота или короткая последовательность. */
  notes: number[];
  /** Длительность одной ноты, секунды. */
  step: number;
  type: OscillatorType;
  gain: number;
};

// Смысл слышен без объяснений: вход — вверх, стоп — вниз, ошибка — резко и
// низко. Прибыль отличается от простой цели тем, что заканчивается выше.
//
// Весь набор опущен на октаву. Прежние ноты жили в области 880-1568 Гц - там,
// где сидят будильник и сигнал микроволновки, - и в тишине кабинета били по
// ушам. Смысл держится на движении между нотами, а не на их высоте: вниз
// читается как вниз в любом регистре, и разбирать сигналы на слух это не
// мешает.
//
// А вот громкость пришлось вернуть. Вслед за нотами сигнал сделали и вдвое
// тише, и под музыкой его не стало слышно вовсе: приглушённое радио звучало
// громче самого сигнала, и о взятой цели сообщал только провал в музыке. Звонок
// убирают не громкостью - её убирают мягкой атакой и срезом верха, и они здесь
// остаются.
const TONES: Record<SoundKind, Tone> = {
  order: { notes: [440], step: 0.06, type: "sine", gain: 0.1 },
  entry: { notes: [330, 440], step: 0.08, type: "sine", gain: 0.13 },
  take: { notes: [440, 587], step: 0.09, type: "sine", gain: 0.13 },
  profit: { notes: [440, 587, 784], step: 0.1, type: "sine", gain: 0.15 },
  stop: { notes: [294, 220], step: 0.11, type: "sine", gain: 0.14 },
  close: { notes: [330, 262], step: 0.09, type: "sine", gain: 0.11 },
  // Треугольник вместо меандра: тот резал слух гармониками, а «резко и низко»
  // держится на самой низкой ноте набора, а не на жёсткости тембра.
  error: { notes: [165, 165], step: 0.13, type: "triangle", gain: 0.12 },
  // Две одинаковые ноты повыше: ни на что не похоже в этом наборе, и трейдер
  // не спутает пересечение уровня со взятой целью.
  alert: { notes: [523, 523], step: 0.11, type: "sine", gain: 0.12 },
  // Награда: два шага вверх, выше и короче цели - не спутать с событием сделки.
  reward: { notes: [587, 784], step: 0.07, type: "sine", gain: 0.12 },
  // Получение: восходящее арпеджио, монеты сыплются в счётчик. Потолок набора
  // тот же, 784 Гц.
  claim: { notes: [392, 523, 659, 784], step: 0.07, type: "sine", gain: 0.14 },
};

/**
 * Срез верха: выше этой частоты сигнал не звенит.
 *
 * Звонкость - это не громкость, а верхние гармоники. Даже у синуса их добавляет
 * сам щелчок включения, и в наушниках он слышен как металлический призвук.
 *
 * Две с небольшим килогерцы, а не полторы: на полутора сигнал становился глухим
 * и в музыке терялся целиком. Самая высокая нота набора - 784 Гц, так что её
 * вторая и третья гармоники проходят, а область будильника остаётся отрезанной.
 */
const TONE_CUTOFF = 2200;

let context: AudioContext | null = null;
let muted = false;

/** Включить или выключить звук. Состояние хранит вызывающий. */
export function setMuted(value: boolean): void {
  muted = value;
}

export function isMuted(): boolean {
  return muted;
}

function ensureContext(): AudioContext | null {
  if (typeof window === "undefined") return null;
  try {
    if (context === null) {
      const Ctor = window.AudioContext ?? (window as unknown as { webkitAudioContext?: typeof AudioContext }).webkitAudioContext;
      if (!Ctor) return null;
      context = new Ctor();
    }
    // После бездействия вкладки контекст засыпает и играет в тишину.
    if (context.state === "suspended") void context.resume();
    return context;
  } catch {
    // Звук — не то, ради чего стоит ронять терминал.
    return null;
  }
}

/**
 * Проиграть сигнал.
 *
 * Ничего не ждёт и ничего не возвращает: звук либо прозвучал, либо нет, и
 * второе не должно мешать работе.
 */
export function play(kind: SoundKind): void {
  if (muted) return;
  const ctx = ensureContext();
  if (!ctx) return;

  const tone = TONES[kind];
  // Музыка отходит на задний план, пока говорит терминал. Сигнал короткий и
  // негромкий - в клубном бите он тонет, а сообщает он о взятой цели или о
  // выбитом стопе. Приглушаем на длину сигнала с небольшим запасом.
  // Считаем по настоящей длине сигнала: последняя нота начинается на своём
  // шаге, а гаснет ещё полтора шага спустя. Вернуть музыку раньше, чем стих
  // хвост, - значит накрыть музыкой то, ради чего её и приглушали.
  duck((tone.notes.length - 1 + 1.6) * tone.step * 1000 + 600);
  const start = ctx.currentTime;

  tone.notes.forEach((frequency, i) => {
    const at = start + i * tone.step;
    const osc = ctx.createOscillator();
    const gain = ctx.createGain();
    // Фильтр на каждую ноту: срезает верхние гармоники, из-за которых сигнал
    // звенел даже на негромкой ноте.
    const soft = ctx.createBiquadFilter();
    soft.type = "lowpass";
    // Значением, а не расписанием: у свежего фильтра срез стоит на 350 Гц, и
    // запись «сменить на 2200 в момент at» оставляла ноту под чужим срезом до
    // самого её начала.
    soft.frequency.value = TONE_CUTOFF;
    // Без подъёма на срезе: он вернул бы ту самую звонкость на самой границе.
    soft.Q.value = 0.7;

    osc.type = tone.type;
    osc.frequency.setValueAtTime(frequency, at);

    // Мягкая атака и долгий спад.
    //
    // Резкое включение слышно как щелчок, и именно он давал сигналу звонкость:
    // ухо ловит не ноту, а удар по ней. Тридцать миллисекунд подъёма этот удар
    // убирают, оставаясь незаметными - сигнал по-прежнему звучит сразу.
    // Спад длиннее самой ноты: звук уходит в тишину, а не обрывается.
    gain.gain.setValueAtTime(0.0001, at);
    gain.gain.exponentialRampToValueAtTime(tone.gain, at + 0.03);
    gain.gain.exponentialRampToValueAtTime(0.0001, at + tone.step * 1.6);

    osc.connect(gain).connect(soft).connect(ctx.destination);
    osc.start(at);
    osc.stop(at + tone.step * 1.6 + 0.02);
  });
}
