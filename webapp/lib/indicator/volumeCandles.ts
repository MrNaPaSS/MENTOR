// Объёмные свечи: толщина тела говорит, чем движение подкреплено.
//
// Обычный график равняет все свечи: рывок на пустом рынке выглядит так же,
// как тот, в который влили десять миллионов. Здесь ширина свечи зависит от её
// объёма - тонкая означает движение без денег, и относиться к нему стоит
// соответственно.
//
// Правила ширины вынесены сюда, отдельно от рисования: это единственная часть
// режима, где можно ошибиться незаметно, и она проверяется тестами.

/** Доля шага сетки, которую занимает свеча обычного объёма. */
const NORMAL_SHARE = 0.68;

/** Границы, за которые ширина не выходит: доли от обычной свечи. */
const THINNEST = 0.18;
const FATTEST = 1.45;

/**
 * Насколько резко толщина следует за объёмом.
 *
 * Единица - прямая пропорция: свеча вчетверо крупнее вчетверо толще и
 * закрывает соседей. Половина (корень) слишком мягкая: свеча на четверти
 * обычного объёма выходит лишь вдвое тоньше, и пустое движение в глаза не
 * бросается. 0.65 - середина: тонкие видно сразу, жирные не наезжают.
 */
const CONTRAST = 0.65;

/**
 * Опорный объём, относительно которого меряются остальные.
 *
 * Медиана, а не среднее: один всплеск на открытии сессии утягивает среднее
 * вверх, и тогда весь остальной график становится одинаково тонким. По медиане
 * обычная свеча остаётся обычной.
 */
export function referenceVolume(volumes: number[]): number {
  const alive = volumes.filter((v) => v > 0).sort((a, b) => a - b);
  if (alive.length === 0) return 0;
  const middle = alive.length >> 1;
  return alive.length % 2 === 1
    ? alive[middle]
    : (alive[middle - 1] + alive[middle]) / 2;
}

/**
 * Ширина свечи в пикселях.
 *
 * Степень от отношения объёмов, а не само отношение: свеча с объёмом вчетверо
 * больше должна быть заметно толще, но не в четыре раза - иначе одна свеча
 * закрывает соседей и график перестаёт читаться. Свеча без объёма при этом
 * обязана быть заметно тоньше обычной: в этом весь смысл режима.
 */
export function candleWidth(volume: number, reference: number, spacing: number): number {
  const normal = Math.max(1, spacing * NORMAL_SHARE);
  if (!(reference > 0) || !(volume > 0)) return normal;

  const scale = Math.min(FATTEST, Math.max(THINNEST, (volume / reference) ** CONTRAST));
  // Не шире шага сетки: соседние свечи не должны наезжать друг на друга.
  return Math.max(1, Math.min(normal * scale, spacing * 0.98));
}
