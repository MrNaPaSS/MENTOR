// Мерка разбора свечи: сколько строк, какой высоты и как далеко бьют следы.
//
// Отдельно от рисования намеренно. Холст проверить нечем - там координаты и
// цвета, - а вот арифметика раскладки решает, читается картинка или нет, и
// ошибка в ней не выглядит ошибкой: свеча нарисуется стройной, просто соврёт о
// том, где прошли деньги.

/**
 * Сколько строк показывает картинка на обычной крупности.
 *
 * Свеча на триста биржевых шагов в столбик не влезает ни на каком экране, а
 * прокручиваемая лента цифр перестаёт быть картинкой свечи.
 *
 * Это потолок для окна обычного размера, а не мерка: на деле строк столько,
 * сколько набрала свеча, и растут они вместе с ней. Настоящий потолок считает
 * само окно - сколько строк полного роста в него влезает.
 */
export const ROWS = 28;

/**
 * Меньше этого лестницу не сжимаем, даже когда холст крошечный.
 *
 * Свеча, схлопнутая в три строки, перестаёт быть профилем: по ней уже не
 * видно ни где стояла цена, ни куда били. Лучше вылезти за край, чем показать
 * три полосы и назвать это разбором.
 */
export const ROWS_MIN = 8;

/** Высота строки в точках: обычная и та, ниже которой цифры сливаются. */
export const ROW = 13;
export const ROW_MIN = 10;

/** Насколько густа самая крупная ячейка и самая мелкая. */
const HEAT_MIN = 0.22;
const HEAT_MAX = 0.62;

/**
 * Высота строки под наличное место.
 *
 * Ужимаем, только если картинка не влезает в холст целиком: обрезанная снизу
 * свеча врёт о том, где она кончилась. Ниже `ROW_MIN` не опускаемся - там
 * цифры сливаются в серую полосу, и лучше обрезать, чем показать нечитаемое.
 */
export function rowHeight(rows: number, room: number): number {
  if (rows <= 0) return ROW;
  return Math.max(ROW_MIN, Math.min(ROW, room / rows));
}

/**
 * Насколько след вылезает за ядро.
 *
 * Корнем от доли, а не долей: на свече, где одна плита вдесятеро больше
 * соседей, доля оставляет от всех остальных следов по два пикселя, и картинка
 * превращается в одну полосу посреди пустоты. Корень растягивает мелочь, не
 * ломая порядка: больший объём всегда бьёт дальше меньшего.
 */
export function traceTail(value: number, peak: number, side: number): number {
  if (!(peak > 0) || !(value > 0)) return 0;
  return side * Math.sqrt(Math.min(1, value / peak));
}

/**
 * Густота ячейки у цены.
 *
 * Ячейка есть у каждой строки, где прошла хоть одна сделка: на ней стоит
 * число, а числу нужна подложка - картинка лежит на голом графике. Поэтому
 * мелочь не уходит в ноль, но остаётся заметно бледнее крупного.
 */
export function cellHeat(value: number, peak: number, ceiling = HEAT_MIN + HEAT_MAX): number {
  if (!(peak > 0) || !(value > 0)) return 0;
  // Потолок приходит снаружи: он считается по цвету палитры так, чтобы цифра
  // на самой густой ячейке осталась читаемой. Ниже нижней границы не опускаем -
  // без заливки ячейка перестаёт быть ячейкой.
  const top = Math.max(HEAT_MIN, Math.min(HEAT_MIN + HEAT_MAX, ceiling));
  return HEAT_MIN + (top - HEAT_MIN) * Math.sqrt(Math.min(1, value / peak));
}

/** Самая густая заливка, какая вообще бывает. По ней считается её предел. */
export const HEAT_TOP = HEAT_MIN + HEAT_MAX;

/** Самая бледная. Ниже неё ячейка сливается с панелью. */
export const HEAT_FLOOR = HEAT_MIN;
