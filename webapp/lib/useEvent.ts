"use client";

// Постоянная ссылка на обработчик, который сам всегда свежий.
//
// Терминал перерисовывается на каждом кадре стакана - восемь раз в секунду. На
// каждой такой перерисовке заново рождаются все стрелочные функции, переданные
// детям: `onClose={() => ...}` это новая ссылка. Ребёнок, обёрнутый в `memo`,
// сравнивает пропсы по ссылке, видит другую функцию и пересчитывает себя
// целиком - защита не срабатывает ни разу.
//
// `useCallback` здесь чаще всего не спасает: обработчик читает половину
// состояния страницы, и честный список зависимостей меняется так же часто.
//
// Поэтому ссылку держим постоянной, а тело подменяем: вызов всегда уходит в ту
// версию функции, что была на последней отрисовке. Логика от этого не меняется
// - меняется только то, что ребёнок перестаёт считать обработчик «другим».
//
// Тело подменяется в `useLayoutEffect`, то есть до того, как браузер отдаст
// пользователю новое событие: обработчик не может увидеть состояние старше
// того, что человек видит на экране.

import { useCallback, useLayoutEffect, useRef } from "react";

export function useEvent<A extends unknown[], R>(fn: (...args: A) => R): (...args: A) => R {
  const held = useRef(fn);

  useLayoutEffect(() => {
    held.current = fn;
  });

  return useCallback((...args: A) => held.current(...args), []);
}
