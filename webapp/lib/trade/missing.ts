// Когда пустой ответ биржи означает закрытую позицию.
//
// Терминал обязан быть зеркалом биржи, но зеркало это кривое: биржа отвечает
// пустым списком позиций и на своей заминке, и тем охотнее, чем чаще её
// спрашивают. Разметка при этом уходит с графика, сделка пишется в журнал, а
// трейдер остаётся с живой позицией на бирже и пустым экраном.
//
// 10 сентября так пропали две сделки по ETH. Выдержка была в два пустых
// ответа, но после первого терминал смотрел второй раз через восемь десятых
// секунды - и обоих хватало: от первой пустоты до похорон прошло 2.2 секунды,
// позиция всё это время стояла на бирже.
//
// Поэтому выдержка меряется временем, а не числом запросов, и последнее слово
// остаётся не за одним ответом биржи, а за согласием двоих - её и
// сопровождения на сервере.

/** Сколько пустых ответов биржи подряд означают закрытую позицию. */
export const MISSING_TOLERANCE = 3;

/**
 * И сколько времени эта пустота должна продержаться.
 *
 * Столько же выдержки по времени держит сопровождение на сервере: два обхода
 * по пять секунд (MISSING_TOLERANCE в backend/trading/watcher.py). Расхождение
 * означало бы, что экран и сервер расходятся во мнении, жива ли сделка.
 */
export const MISSING_HOLD_MS = 10_000;

/**
 * Не чаще этого засчитываем пустой ответ.
 *
 * Круги опроса бывают чаще выдержки - от переподключения, от возвращения на
 * вкладку, от соседней сделки на той же монете. Промах, засчитанный дважды за
 * секунду, - это не два мнения биржи, а одно.
 */
export const MISSING_STEP_MS = 2000;

/** Пустота по одной сделке: когда началась, когда засчитана, сколько промахов. */
export type Miss = { since: number; at: number; seen: number };

/**
 * Засчитать пустой ответ.
 *
 * Возвращает новую отметку, не трогая прежнюю: слишком частый повтор
 * возвращает её как есть - тот же ответ биржи не становится вторым мнением от
 * того, что его спросили дважды.
 */
export function noteMiss(was: Miss | undefined, now: number): Miss {
  if (was && now - was.at < MISSING_STEP_MS) return was;
  return { since: was?.since ?? now, at: now, seen: (was?.seen ?? 0) + 1 };
}

/**
 * Пора ли хоронить сделку.
 *
 * `server` - что говорит сопровождение: `true` - сделка у него в работе,
 * `false` - оно её не ведёт, `null` - не спросили или не ответило.
 *
 * Хороним только при согласии обоих. Пока сервер сделку ведёт, пустой ответ
 * биржи был заминкой; не ответил и он - тоже ждём. Пустой экран при живой
 * позиции дороже лишней минуты разметки на графике.
 */
export function shouldBury(miss: Miss, now: number, server: boolean | null): boolean {
  if (miss.seen < MISSING_TOLERANCE) return false;
  if (now - miss.since < MISSING_HOLD_MS) return false;
  return server === false;
}
