// Предпросмотр ссылки, который можно сделать без сервера.
//
// Настоящий предпросмотр - это заголовок и картинка со страницы, а за ними
// нужно сходить на чужой домен. Из браузера так не сходишь: чужие сайты не
// разрешают читать себя со стороны, и запрос отобьётся молча. Значит, либо
// проксировать через свой бэкенд, либо показывать то, что видно из самой
// ссылки.
//
// Пока второе. Из ссылки честно читаются домен и путь, а картинка по прямой
// ссылке - это уже настоящий предпросмотр: её и показываем целиком.

const URL_RE = /https?:\/\/[^\s<>"']+/i;
const IMAGE_RE = /\.(png|jpe?g|gif|webp|avif|svg)(\?|#|$)/i;

export type LinkCard = {
  href: string;
  /** Домен без www: он и есть главное, что говорит о ссылке. */
  host: string;
  /** Путь с запросом, обрезанный: длинные ссылки ломают узкую панель. */
  rest: string;
  /** Ссылка ведёт прямо на картинку - её можно показать. */
  image: boolean;
};

/** Первая ссылка в сообщении. Их бывает несколько, но карточка нужна одна. */
export function firstLink(text: string): LinkCard | null {
  const found = text.match(URL_RE);
  if (!found) return null;

  // Знаки препинания в конце - часть фразы, а не адреса: «смотри тут: a.com.»
  const href = found[0].replace(/[.,;:!?)\]]+$/, "");
  try {
    const url = new URL(href);
    const rest = `${url.pathname}${url.search}`.replace(/^\/$/, "");
    return {
      href,
      host: url.hostname.replace(/^www\./, ""),
      rest: rest.length > 48 ? `${rest.slice(0, 47)}…` : rest,
      image: IMAGE_RE.test(url.pathname),
    };
  } catch {
    // Не адрес, а что-то на него похожее.
    return null;
  }
}
