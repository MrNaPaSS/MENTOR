// Адрес картинки из чата в том виде, в каком его откроет браузер ученика.
//
// Фото из форума сервер сохраняет у себя и записывает полным адресом. Адрес он
// собирает из запроса бота, а бот стучится изнутри того же стола - на
// 127.0.0.1:8000. Без SHOTS_BASE_URL в сообщение уходил этот внутренний адрес,
// и у ученика вместо фото стоял знак сломанной картинки: и на компьютере, и на
// планшете. Путь при этом верный, неверен только хост - его и подменяем на тот,
// по которому сайт ходит в API. Уже записанные сообщения чинятся тем же.

const LOOPBACK = /^https?:\/\/(?:localhost|127\.0\.0\.1|\[::1\])(?::\d+)?(?=\/|$)/i;

export function publicAsset(url: string | null | undefined, apiBase: string): string {
  if (!url) return "";
  if (!LOOPBACK.test(url)) return url;
  // Сайт сам работает на локальном API - в разработке внутренний адрес верен.
  if (!apiBase || LOOPBACK.test(apiBase)) return url;
  return url.replace(LOOPBACK, apiBase.replace(/\/+$/, ""));
}
