"use client";

// Профиль изменился — оболочке нужно об этом знать.
//
// Шапка сайта читает профиль один раз, при входе в кабинет. Баланс в ней
// оттуда же, и пока он не менялся, этого хватало. Но менялся: новый ученик
// подключает ключи WEEX уже внутри кабинета, счёт после этого перестаёт быть
// нулём, а шапка об этом не знает — и показывает ноль до перезагрузки страницы.
//
// Событие закрывает эту дыру изнутри вкладки: страница, обновившая профиль,
// говорит об этом вслух, оболочка перечитывает его и меняет цифру там же, где
// человек её и ждёт. Снаружи вкладки профиль меняется редко, и на этот случай
// оболочка перечитывает его сама — на переходах между разделами и при возврате
// на вкладку.

/** Имя события. То же соглашение, что у монет: `nmnh-<что>-updated`. */
export const PROFILE_EVENT = "nmnh-profile-updated";

/** Сказать оболочке, что профиль пора перечитать. */
export function profileChanged(): void {
  if (typeof window === "undefined") return;
  window.dispatchEvent(new Event(PROFILE_EVENT));
}
