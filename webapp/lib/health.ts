// Жив ли сервер - глазами браузера.
//
// Фронт и бэкенд живут на разных машинах: страница отдаётся хостингом, а API
// приходит туннелем с рабочего стола. Когда туннель закрыт - на обновлении, на
// перезагрузке, - страница остаётся открытой и работает, а каждый её запрос
// падает. Человек видит пустые виджеты и нули вместо цен и решает, что сломан
// сайт, хотя сломана связь с ним.
//
// Поэтому состояние сервера - общее знание всего приложения, а не забота
// каждого виджета по отдельности. Кто ходит по сети, сообщает сюда об удаче и
// промахе; кто рисует - подписывается и показывает экран обновления.
//
// Один промах экраном не считается. Оборванный на переключении сети запрос -
// обычное дело, и закрывать из-за него весь терминал значит пугать человека
// там, где ничего не случилось.

/** Что мы сейчас думаем о сервере. */
export type Health = "up" | "down";

// Столько промахов подряд - и только тогда экран. Два: первый бывает у любого
// запроса, два подряд бывают только у лежащего сервера.
const MISSES_TO_FALL = 2;

// Как часто стучаться, пока сервер молчит. Пять секунд - это заметно быстрее,
// чем человек успевает потянуться к F5, и заметно реже, чем нужно, чтобы
// туннель считал нас за наплыв.
const PROBE_MS = 5000;

let state: Health = "up";
let misses = 0;
let timer: ReturnType<typeof setInterval> | null = null;
let probe: (() => Promise<boolean>) | null = null;

const listeners = new Set<(next: Health) => void>();

/** Текущее состояние. Нужно тем, кто подключается позже первого промаха. */
export function serverHealth(): Health {
  return state;
}

/**
 * Чем проверять сервер, когда он молчит.
 *
 * Ставит клиент API: адрес бэкенда знает он, а этот модуль про сеть ничего не
 * знает намеренно - иначе адрес пришлось бы собирать в двух местах.
 */
export function setHealthProbe(fn: () => Promise<boolean>): void {
  probe = fn;
}

/** Следить за состоянием. Возвращает отписку. */
export function watchHealth(fn: (next: Health) => void): () => void {
  listeners.add(fn);
  return () => {
    listeners.delete(fn);
  };
}

function announce(next: Health): void {
  if (state === next) return;
  state = next;
  listeners.forEach((fn) => fn(next));
}

/** Запрос дошёл. Сервер жив - и счёт промахов начинается заново. */
export function apiAlive(): void {
  misses = 0;
  if (timer !== null) {
    clearInterval(timer);
    timer = null;
  }
  announce("up");
}

/**
 * Запрос не дошёл: сеть оборвалась или Cloudflare ответил за отсутствующий
 * сервер (520-530, среди них та самая 1033 - «туннеля нет»).
 */
export function apiDown(): void {
  misses += 1;
  if (misses < MISSES_TO_FALL) return;
  announce("down");
  startProbing();
}

/**
 * Стучаться, пока не ответит.
 *
 * Своим опросом, а не ожиданием чужих запросов: пока экран закрыт, приложение
 * ничего не запрашивает, и без опроса он остался бы висеть до перезагрузки
 * страницы - ровно того действия, которого мы хотим избежать.
 */
function startProbing(): void {
  if (timer !== null || probe === null) return;
  timer = setInterval(async () => {
    if (!probe) return;
    let ok = false;
    try {
      ok = await probe();
    } catch {
      ok = false;
    }
    if (ok) apiAlive();
  }, PROBE_MS);
}

/**
 * Ответ сервера считаем неудачей самого сервера, а не запроса.
 *
 * 502-504 - это прокси без бэкенда за ним, 520-530 - Cloudflare без туннеля.
 * Всё остальное, включая 401 и 404, значит, что сервер на месте и ответил.
 */
export function isServerGone(status: number): boolean {
  return status === 502 || status === 503 || status === 504 || (status >= 520 && status <= 530);
}
