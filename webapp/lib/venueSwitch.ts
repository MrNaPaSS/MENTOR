// Сменил ли трейдер биржу - или терминал просто узнал, на какой он.
//
// Отдельным файлом и чистой функцией, потому что ошибка здесь не видна в коде,
// а видна только глазами: после каждой перезагрузки терминал сам уходил на
// биткоин, хотя трейдер работал с другой парой.

/**
 * Смена биржи - только переход с одной известной биржи на другую.
 *
 * До ответа сервера по счёту биржа пустая. Пустое значение попадало в память
 * как «прежняя биржа», и когда приезжала настоящая, это выглядело сменой:
 * запомненная пара затиралась биткоином на каждом открытии терминала.
 */
export function isVenueSwitch(was: string | null, now: string): boolean {
  if (!was || !now) return false;
  return was !== now;
}
