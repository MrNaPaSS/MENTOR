// Возврат графика к цене после прогулки по истории.
//
// График не следует за ценой, пока его увели назад: библиотека прекращает
// прокрутку, как только диапазон сдвинули руками. Это правильно, пока человек
// смотрит историю, и неправильно через минуту после - трейдер отвлёкся, цена
// ушла, а на экране позавчерашние свечи.
//
// Здесь только решение: ушли ли мы от цены и не пора ли вернуться. Сам возврат
// делает график, а такую развилку можно проверить тестом.

/** Видимый кусок шкалы в номерах свечей - то, что отдаёт библиотека. */
export interface LogicalRange {
  from: number;
  to: number;
}

/**
 * Сколько ждать до возврата.
 *
 * Полминуты: хватает, чтобы разглядеть вчерашний разворот, и мало, чтобы
 * пропустить движение. Отсчёт начинается заново от каждого движения графика,
 * поэтому пока человек листает, возврат не случится.
 */
export const RETURN_TO_LIVE_MS = 30_000;

/**
 * Насколько далеко от последней свечи считается «ушли в историю».
 *
 * Справа у графика своё пустое поле под бокс сделки, и в живом положении
 * правый край диапазона стоит за последней свечой. Поэтому меряем с запасом:
 * пара свечей туда-сюда - это не прогулка по истории, а дрожь при прокрутке.
 */
export const HISTORY_GAP_BARS = 3;

/** Ушёл ли график от цены. */
export function inHistory(
  range: LogicalRange | null | undefined,
  total: number,
): boolean {
  if (!range || total <= 0) return false;
  return range.to < total - HISTORY_GAP_BARS;
}

/** Двинулся ли диапазон: сравнение с прошлым замером, а не с данными. */
export function rangeMoved(
  before: LogicalRange | null,
  now: LogicalRange | null | undefined,
): boolean {
  if (!now) return false;
  if (!before) return true;
  // Полсвечи - это не движение: библиотека шлёт мелкие поправки сама, когда
  // приезжают новые данные, и от них отсчёт перезапускаться не должен.
  return Math.abs(before.from - now.from) > 0.5 || Math.abs(before.to - now.to) > 0.5;
}
