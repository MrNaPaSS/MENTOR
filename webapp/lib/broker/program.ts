/**
 * Условия брокерской программы: биржи, ставки, уровни возврата.
 *
 * Один файл на всю страницу /broker. Проценты на витрине - обещание, и
 * обещание, размазанное по десятку компонентов, однажды разойдётся само с
 * собой: в шапке будет 30%, в таблице 25%, а в калькуляторе третье число.
 * Поэтому цифра живёт здесь ровно в одном экземпляре, а разметка её только
 * показывает.
 *
 * Ставки бирж - публичные, базовый уровень (VIP 0), фьючерсы USDT-M.
 * Проверено 10 сентября 2026; у WEEX то же значение стоит в фильтрах ядра
 * (core/weex/futures.py, taker_fee 0.0008).
 *
 * Экономика и ограничения - из docs/integrations/broker-program-plan.md, §2.
 */

/** Состояние биржи в программе. Врать здесь нельзя: это читает будущий клиент. */
export type ExchangeStatus =
  /** Подключена, торговля и возврат работают сегодня. */
  | "live"
  /**
   * Ещё не подключена.
   *
   * Одно слово на все неподключённые биржи намеренно. Промежуточные степени
   * готовности - «партнёрство есть», «заявка подана» - читаются как обещание
   * срока, которого мы не давали: для трейдера разницы нет, торговать нельзя
   * ни там, ни там.
   */
  | "soon";

export interface Exchange {
  id: string;
  name: string;
  status: ExchangeStatus;
  /** Ставка мейкера в долях единицы: 0.0002 - это 0.02%. */
  makerRate: number;
  takerRate: number;
}

/**
 * Биржи по порядку показа.
 *
 * Первой идёт та, что работает. Соблазн поставить вперёд Binance ради узнавания
 * прямой обман: человек кликнет и упрётся в «скоро».
 */
export const EXCHANGES: readonly Exchange[] = [
  { id: "weex", name: "WEEX", status: "live", makerRate: 0.0002, takerRate: 0.0008 },
  { id: "bingx", name: "BingX", status: "soon", makerRate: 0.0002, takerRate: 0.0005 },
  { id: "bybit", name: "Bybit", status: "soon", makerRate: 0.0002, takerRate: 0.00055 },
  { id: "okx", name: "OKX", status: "soon", makerRate: 0.0002, takerRate: 0.0005 },
  { id: "binance", name: "Binance", status: "soon", makerRate: 0.0002, takerRate: 0.0005 },
  { id: "bitget", name: "Bitget", status: "soon", makerRate: 0.0002, takerRate: 0.0006 },
] as const;

/** Биржа, с которой открывается калькулятор: единственная работающая. */
export const DEFAULT_EXCHANGE = EXCHANGES[0];

export function exchangeById(id: string): Exchange {
  return EXCHANGES.find((e) => e.id === id) ?? DEFAULT_EXCHANGE;
}

export interface CashbackTier {
  id: string;
  /** Нижняя граница оборота за 30 дней в USDT, включительно. */
  fromVolume: number;
  /** Доля комиссии трейдера, которая к нему возвращается. */
  share: number;
}

/**
 * Уровни возврата - по обороту за 30 дней, как VIP у самой биржи.
 *
 * Ключевое отличие от подписочных брокеров: уровень нельзя купить. Он растёт
 * от того, сколько человек торгует, а не сколько заплатил, и поэтому наш
 * интерес совпадает с его интересом, а не противостоит ему.
 *
 * Верхний уровень упирается в потолок из MIN_MARGIN намеренно: выше него
 * возврат съел бы весь ребейт, и программа существовала бы в убыток.
 */
export const CASHBACK_TIERS: readonly CashbackTier[] = [
  { id: "base", fromVolume: 0, share: 0.25 },
  { id: "active", fromVolume: 1_000_000, share: 0.3 },
  { id: "pro", fromVolume: 5_000_000, share: 0.35 },
  { id: "top", fromVolume: 20_000_000, share: 0.4 },
] as const;

/**
 * Доля комиссии, которую биржа отдаёт нам.
 *
 * Договорная и у каждой биржи своя; 50% - то, из чего считает план (§2). Пока
 * договор не подписан, число живёт только внутри расчёта потолка и на витрину
 * не выносится: обещать чужую ставку до подписи нельзя.
 */
export const REBATE_SHARE = 0.5;

/**
 * Сколько от комиссии трейдера обязано остаться у NMNH.
 *
 * Не жадность, а предохранитель: партнёрские ставки биржи пересматриваются
 * (у Binance - ежеквартально), и фиксированная доля трейдера при снижении
 * ставки съедает маржу целиком. Отсюда потолок возврата в cashbackShare().
 */
export const MIN_MARGIN = 0.1;

/** Обозримый горизонт калькулятора: год. Экономия за месяц выглядит мелочью. */
export const YEAR_MONTHS = 12;
