import type { FaqItem } from "@/lib/seo/jsonLd";

/** Смысловой блок страницы: заголовок второго уровня и текст под ним. */
export interface SeoSection {
  heading: string;
  paragraphs: readonly string[];
  bullets?: readonly string[];
}

/** Ссылка на соседнюю страницу витрины. */
export interface SeoLink {
  path: string;
  label: string;
  hint: string;
}

/** Шаг разбора со снимком терминала: что было видно и что из этого вышло. */
export interface SeoStep {
  title: string;
  text: string;
  src: string;
  alt: string;
}

/**
 * Разбор одной сделки снимками.
 *
 * Страница под запрос объясняет словами, а это показывает: те же снимки, что
 * трейдер видел у себя. Шаги идут подряд и все сразу - ни листания, ни
 * раскрытия по клику: текст и картинки, ради которых страницу находят, должны
 * быть в исходном HTML.
 */
export interface SeoExample {
  heading: string;
  intro: string;
  steps: readonly SeoStep[];
  /** Чем сделка кончилась: карточка терминала и она же на бирже. */
  cards?: readonly { src: string; alt: string; caption: string }[];
}

/**
 * Витрина карточек сделок: наш бланк против биржевого.
 *
 * Сами сделки приходят из `lib/showcase` - того же списка, по которому
 * нарисованы картинки. Здесь только слова вокруг них.
 */
export interface SeoShowcase {
  heading: string;
  intro: string;
  /** Подписи чисел над витриной. */
  statPnl: string;
  statBest: string;
  statVenues: string;
  /** Оговорка про плечо: обещание доходности - то, за что перестают верить. */
  honest: string;
  /** Подпись под нашей карточкой в паре. */
  theirs: string;
}

/**
 * Страница витрины, написанная под поисковый запрос.
 *
 * Текст отделён от вёрстки намеренно: страниц четыре, устроены они одинаково,
 * и правится в них обычно слово, а не разметка. Держа слова отдельно, их можно
 * менять, не трогая ни одного тега - и не ломая то, что уже нашёл поисковик.
 */
export interface SeoPage {
  /** Путь от корня; он же уходит в canonical, sitemap и хлебные крошки. */
  path: string;
  /** Строка в выдаче. До 60 знаков - дальше Google обрезает многоточием. */
  title: string;
  /** Описание под строкой выдачи. До 160 знаков по той же причине. */
  description: string;
  /** Надпись над заголовком: раздел, к которому страница относится. */
  eyebrow: string;
  /** Единственный H1 страницы. */
  h1: string;
  /** Первый абзац: он же чаще всего попадает в сниппет выдачи. */
  lead: string;
  /**
   * Картинка под первым абзацем: как выглядит то, о чём страница.
   *
   * Необязательная. Текст важнее - он и есть причина, по которой страницу
   * находят, - поэтому картинка идёт после него и грузится лениво, не
   * задерживая первый экран.
   */
  cover?: { src: string; alt: string };
  sections: readonly SeoSection[];
  /** Разбор сделки снимками - там, где он к месту. Идёт после разделов. */
  example?: SeoExample;
  /** Витрина карточек сделок - там, где она к месту. Идёт после разбора. */
  showcase?: SeoShowcase;
  faq: readonly FaqItem[];
  cta: { heading: string; text: string };
  /** Соседние страницы: обход сайта идёт по ссылкам, а не по угадыванию. */
  related: readonly SeoLink[];
}

/**
 * Текст под открытым инструментом, например калькулятором.
 *
 * Сам инструмент рисуется в браузере, и в исходном HTML от него остаётся
 * пустая рамка. Этот текст - то, что поисковик на такой странице прочтёт.
 */
export interface SeoToolPage {
  path: string;
  /** Строка в выдаче, до 60 знаков. */
  title: string;
  /** Описание под строкой выдачи, до 160 знаков. */
  description: string;
  /** Имя страницы в разметке и хлебных крошках. */
  name: string;
  sections: readonly SeoSection[];
  faq: readonly FaqItem[];
  related: readonly SeoLink[];
}
