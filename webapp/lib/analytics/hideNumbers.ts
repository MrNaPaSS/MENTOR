"use client";

// Цифры счёта под звёздочками.
//
// Аналитику открывают не только наедине: разбор в трансляции, экран на созвоне,
// скриншот в чат. Оборот и пополнения - те цифры, которые показывать не всегда
// хочется, а закрывать их рукой или обрезать снимок неудобно.
//
// Выбор запоминается: закрыл однажды - раздел так и открывается закрытым, пока
// не откроют обратно. Память браузерная и своя у каждого устройства: на рабочей
// машине можно держать цифры открытыми, а на ноутбуке для встреч - закрытыми.

export const HIDE_KEY = "nmnh.analytics.hidden";

/** Чем заменяются цифры. Длина постоянная: по ней не угадать порядок суммы. */
export const MASK = "*****";

/** Закрыты ли цифры. По умолчанию открыты: скрывает их человек, а не мы. */
export function numbersHidden(): boolean {
  try {
    return localStorage.getItem(HIDE_KEY) === "1";
  } catch {
    // Приватное окно или запрет на хранилище - показываем как обычно.
    return false;
  }
}

/** Запомнить выбор. */
export function rememberHidden(hidden: boolean): void {
  try {
    if (hidden) localStorage.setItem(HIDE_KEY, "1");
    else localStorage.removeItem(HIDE_KEY);
  } catch {
    // Не запомнилось - не беда: в этом окне выбор всё равно работает.
  }
}

/**
 * Значение строки: само число или звёздочки.
 *
 * Прочерк остаётся прочерком: скрывать нечего, а звёздочки на его месте
 * выглядели бы как спрятанная цифра, которой нет.
 */
export function maskValue(value: string, hidden: boolean): string {
  if (!hidden || value === "-") return value;
  return MASK;
}
