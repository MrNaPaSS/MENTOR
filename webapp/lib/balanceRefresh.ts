// Обновление баланса после сделок.
//
// Баланс в терминале освежался только при открытии страницы и кнопкой в
// профиле. После входа и выхода цифра устаревала, и окно заявки считало
// свободные деньги от неё: писало «больше 2 $ не пройдёт», когда деньги на
// счёте были.
//
// Отдельным файлом и без React, чтобы проверить тестом с поддельными часами:
// ошибка здесь - это либо лишние запросы к бирже, либо баланс, который так и
// не обновился.

/** Сколько ждать после события: биржа пересчитывает маржу не мгновенно. */
export const BALANCE_DELAY_MS = 1500;

export type BalanceRefresher = {
  /** Попросить обновление. Просьбы подряд склеиваются в один запрос. */
  request(): void;
  /** Забыть отложенный запрос - страница закрывается. */
  cancel(): void;
};

/**
 * Отложенное обновление баланса.
 *
 * Вход, набор позиции и выставленные цели приходят пачкой за секунду-другую,
 * и на каждое событие ходить на биржу незачем: запрос уходит один, через
 * `delay` после последней просьбы.
 */
export function createBalanceRefresher(
  refresh: () => void | Promise<void>,
  delay: number = BALANCE_DELAY_MS,
): BalanceRefresher {
  let timer: ReturnType<typeof setTimeout> | null = null;
  return {
    request() {
      if (timer !== null) clearTimeout(timer);
      timer = setTimeout(() => {
        timer = null;
        void Promise.resolve()
          .then(refresh)
          .catch(() => {
            // Баланс не обновился - останется прежний, это не повод ронять экран.
          });
      }, delay);
    },
    cancel() {
      if (timer !== null) clearTimeout(timer);
      timer = null;
    },
  };
}
