import { describe, it, expect } from "vitest";
import { goneTakes } from "@/lib/trade/exchange";

// Цель, которую биржа не приняла при постановке, не взята. Терминал считал
// «ушедшие» цели от замысла, и у сделки с тремя целями в плане и двумя
// вставшими писал «взята цель 1» сразу после входа.

describe("ушедшие с биржи цели", () => {
  it("невставшая цель не считается взятой", () => {
    expect(goneTakes(3, 2, [1126.77, 1123.82])).toBe(0);
  });

  it("исполнившаяся цель считается", () => {
    expect(goneTakes(3, 3, [1127.32, 1122.64])).toBe(1);
    expect(goneTakes(3, 2, [1123.82])).toBe(1);
  });

  it("лестницы не было - считать нечего", () => {
    expect(goneTakes(3, 0, [])).toBe(0);
  });

  it("биржа не назвала цены - считать нечего", () => {
    expect(goneTakes(3, 3, null)).toBe(0);
    expect(goneTakes(3, 3, undefined)).toBe(0);
  });

  it("стоящих больше, чем в лестнице, - не уходит в минус", () => {
    expect(goneTakes(3, 6, [1, 2, 3, 4, 5, 6])).toBe(0);
  });
});
