import { describe, it, expect } from "vitest";
import { isNearBottom } from "@/lib/chat/stickToBottom";

// Чат открывался не у последнего сообщения: плавная прокрутка уезжала мимо
// конца, пока догружались картинки и обложки ссылок. Теперь лента держится
// внизу, пока человек сам не ушёл листать историю.

describe("лента чата у последнего сообщения", () => {
  it("ровно внизу", () => {
    expect(isNearBottom(1000, 600, 400)).toBe(true);
  });

  it("пара десятков пикселей до конца - всё ещё внизу", () => {
    expect(isNearBottom(1000, 560, 400)).toBe(true);
  });

  it("ушёл листать историю - не внизу", () => {
    expect(isNearBottom(1000, 200, 400)).toBe(false);
  });

  it("сообщений меньше, чем места, - внизу", () => {
    expect(isNearBottom(300, 0, 400)).toBe(true);
  });
});
