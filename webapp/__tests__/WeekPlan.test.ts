/**
 * Неделя по ISO.
 *
 * План лежит по номеру недели, а не по дате её начала: неделя у разных стран
 * начинается по-разному, а номер по ISO один и тот же везде. Год недели - это
 * год её четверга, поэтому конец декабря попадает в первую неделю января, а
 * начало января иногда в последнюю неделю прошлого года.
 */

import { describe, it, expect } from "vitest";

import { isoWeek } from "@/lib/weekPlan";

const utc = (iso: string) => new Date(`${iso}T12:00:00Z`);

describe("номер недели", () => {
  it("считает обычную неделю", () => {
    // Четверг 17 сентября 2026 - 38-я неделя.
    expect(isoWeek(utc("2026-09-17"))).toBe("2026-W38");
    // Понедельник и воскресенье той же недели дают тот же номер.
    expect(isoWeek(utc("2026-09-14"))).toBe("2026-W38");
    expect(isoWeek(utc("2026-09-20"))).toBe("2026-W38");
  });

  it("новая неделя начинается с понедельника", () => {
    expect(isoWeek(utc("2026-09-21"))).toBe("2026-W39");
  });

  it("конец года уходит в неделю своего четверга", () => {
    // 31 декабря 2025 - среда, её четверг уже в 2026 году.
    expect(isoWeek(utc("2025-12-31"))).toBe("2026-W01");
    // 1 января 2027 - пятница, четверг той недели ещё в 2026-м.
    expect(isoWeek(utc("2027-01-01"))).toBe("2026-W53");
  });

  it("номер всегда двузначный: по нему сортируют строками", () => {
    expect(isoWeek(utc("2026-01-08"))).toBe("2026-W02");
  });
});
