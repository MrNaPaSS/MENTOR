"use client";

// Экран «сервер обновляется».
//
// Сайт отдаётся хостингом и стоит на ногах всегда; API приходит туннелем с
// рабочего стола и пропадает вместе с ним - на обновлении, на перезапуске, на
// перезагрузке машины. Страница в это время открыта и по виду исправна: меню
// нажимается, вкладки переключаются, а цифр нет нигде. Это худший вид поломки -
// тот, который выглядит как рабочее приложение.
//
// Поэтому вместо пустого терминала - честная заслонка на весь экран: сервер
// обновляется, вернётся сам, трогать ничего не нужно. Она же снимается сама -
// наблюдатель (lib/health.ts) стучится в сервер, пока тот не ответит.
//
// Заслонка накрывает и кабинет, и посадочную: молчащий сервер одинаково не даёт
// ни войти, ни посмотреть.

import { useEffect, useState } from "react";

import MaintenanceScreen from "./MaintenanceScreen";
import { serverHealth, watchHealth } from "@/lib/health";

export default function ServerUpdating() {
  const [down, setDown] = useState(false);

  useEffect(() => {
    setDown(serverHealth() === "down");
    return watchHealth((next) => setDown(next === "down"));
  }, []);

  if (!down) return null;

  return (
    <MaintenanceScreen
      title="Сервер обновляется"
      note="Терминал вернётся через пару минут. Обновлять страницу не нужно, он включится сам, как только сервер ответит."
    />
  );
}
