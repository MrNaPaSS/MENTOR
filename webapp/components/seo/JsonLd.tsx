import type { JsonLdNode } from "@/lib/seo/jsonLd";

/**
 * Разметка Schema.org на странице.
 *
 * Узлы кладём в один `@graph`, а не в несколько тегов подряд: так они могут
 * ссылаться друг на друга по `@id` - страница на сайт, сайт на организацию, -
 * и поисковик видит одно связанное описание вместо трёх разрозненных.
 *
 * Компонент серверный: разметка обязана быть в исходном HTML. Дорисованную
 * скриптом её читает не всякий обходчик, а те, кто читает, - не сразу.
 */
export default function JsonLd({ nodes }: { nodes: readonly JsonLdNode[] }) {
  const graph = { "@context": "https://schema.org", "@graph": nodes };

  return (
    <script
      type="application/ld+json"
      // Разметка - наши собственные строки из словаря, не пользовательский
      // ввод. Экранируем «<» на случай, если в тексте однажды окажется тег:
      // иначе он закроет скрипт посреди разметки и сломает страницу.
      dangerouslySetInnerHTML={{
        __html: JSON.stringify(graph).replace(/</g, "\u003c"),
      }}
    />
  );
}
